import fs from "node:fs";
import postgres from "postgres";
const env = fs.readFileSync(new URL("./.env", import.meta.url), "utf8");
const url = env.match(/^DATABASE_URL=(.*)$/m)[1].trim().replace(/^["']|["']$/g, "");
const sql = postgres(url, { max: 1 });

const enums = await sql`SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid GROUP BY t.typname`;
const enumMap = Object.fromEntries(enums.map(r => [r.typname, r.labels]));
console.log("existing enums:", JSON.stringify(enumMap));
const cols = await sql`SELECT column_name, data_type, udt_name FROM information_schema.columns WHERE table_name = 'cs_tickets' ORDER BY ordinal_position`;
console.log("cs_tickets columns:", JSON.stringify(cols));
const tableList = await sql`SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_name LIKE 'cs%'`;
console.log("cs tables:", JSON.stringify(tableList));

const colMap = Object.fromEntries(cols.map(c => [c.column_name, c]));
const steps = [];
const statusCol = colMap["status"];
if (statusCol && statusCol.data_type === "USER-DEFINED") {
  steps.push([`ALTER TYPE ${statusCol.udt_name} ADD VALUE IF NOT EXISTS '확인 중'`, `add '확인 중' to enum ${statusCol.udt_name}`]);
} else {
  console.log("status column:", JSON.stringify(statusCol), "-> text column, enum step skipped");
}
if (!enumMap["ticket_check"]) steps.push([`DO $$ BEGIN CREATE TYPE ticket_check AS ENUM ('대리점 확인중','기사 확인중'); EXCEPTION WHEN duplicate_object THEN NULL; END $$`, "create enum ticket_check"]);
if (!colMap["checkDetail"]) steps.push([`ALTER TABLE cs_tickets ADD COLUMN IF NOT EXISTS "checkDetail" ticket_check`, "add cs_tickets.checkDetail"]);
if (!colMap["isIssue"]) steps.push([`ALTER TABLE cs_tickets ADD COLUMN IF NOT EXISTS "isIssue" boolean NOT NULL DEFAULT false`, "add cs_tickets.isIssue"]);
if (!colMap["issueNote"]) steps.push([`ALTER TABLE cs_tickets ADD COLUMN IF NOT EXISTS "issueNote" text NOT NULL DEFAULT ''`, "add cs_tickets.issueNote"]);
if (!colMap["feedbackAt"]) steps.push([`ALTER TABLE cs_tickets ADD COLUMN IF NOT EXISTS "feedbackAt" timestamp`, "add cs_tickets.feedbackAt"]);
if (!colMap["feedbackSeenAt"]) steps.push([`ALTER TABLE cs_tickets ADD COLUMN IF NOT EXISTS "feedbackSeenAt" timestamp`, "add cs_tickets.feedbackSeenAt"]);
const hasEventsTable = tableList.some(t => t.table_name === "cs_ticket_events");
const roleCol = colMap["createdByRole"];
const actorType = roleCol && roleCol.data_type === "USER-DEFINED" ? roleCol.udt_name : (enumMap["ticket_actor"] ? "ticket_actor" : "text");
if (!hasEventsTable) {
  steps.push([`CREATE TABLE IF NOT EXISTS cs_ticket_events (
     id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
     "ticketCode" varchar(24) NOT NULL,
     "actorUserId" integer NOT NULL,
     "actorRole" ${actorType} NOT NULL,
     "actorName" varchar(100) NOT NULL DEFAULT '',
     action text NOT NULL,
     "createdAt" timestamp NOT NULL DEFAULT now()
   )`, `create cs_ticket_events (actorRole: ${actorType})`]);
}
for (const [statement, label] of steps) {
  await sql.unsafe(statement);
  console.log("ok:", label);
}
if (!hasEventsTable && cols.length > 0) {
  const roleExpr = actorType === "text" ? `"createdByRole"::text` : `"createdByRole"`;
  await sql.unsafe(`INSERT INTO cs_ticket_events ("ticketCode", "actorUserId", "actorRole", "actorName", action)
    SELECT "ticketCode", "createdByUserId", ${roleExpr}, '', 'CS 접수 (기존 티켓 자동 기록) · 유형 ' || type::text
    FROM cs_tickets
    WHERE NOT EXISTS (SELECT 1 FROM cs_ticket_events e WHERE e."ticketCode" = cs_tickets."ticketCode")`);
  console.log("ok: backfill history events for existing tickets");
}
const finalCols = await sql`SELECT column_name, data_type, udt_name FROM information_schema.columns WHERE table_name = 'cs_ticket_events' ORDER BY ordinal_position`;
console.log("cs_ticket_events columns:", JSON.stringify(finalCols));
const statusValues = statusCol && statusCol.data_type === "USER-DEFINED" ? await sql`SELECT enum_range(NULL::${sql(statusCol.udt_name)}) AS r`.catch(() => null) : null;
if (statusValues) console.log("status enum values:", JSON.stringify(statusValues[0].r));
const count = await sql`SELECT count(*)::int AS n FROM cs_ticket_events`;
console.log("cs_ticket_events rows:", count[0].n);
await sql.end();
