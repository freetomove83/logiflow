import { readFileSync } from "node:fs";
const databaseUrl = readFileSync(new URL("../.env", import.meta.url), "utf8").match(/^DATABASE_URL="?([^"\r\n]+)"?/m)?.[1];
if (!databaseUrl) throw new Error("DATABASE_URL not found in .env");
const postgres = (await import("postgres")).default;
const sql = postgres(databaseUrl, { max: 1 });
await sql`CREATE TABLE IF NOT EXISTS agency_announcements (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "agencyUserId" integer NOT NULL,
  "createdByUserId" integer NOT NULL,
  title varchar(120) NOT NULL,
  body text NOT NULL,
  "startsAt" timestamp NOT NULL DEFAULT now(),
  "endsAt" timestamp NOT NULL,
  "createdAt" timestamp NOT NULL DEFAULT now()
)`;
await sql`CREATE TABLE IF NOT EXISTS agency_announcement_reads (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  "announcementId" integer NOT NULL,
  "userId" integer NOT NULL,
  "readAt" timestamp NOT NULL DEFAULT now()
)`;
await sql`CREATE UNIQUE INDEX IF NOT EXISTS announcement_read_unique ON agency_announcement_reads ("announcementId", "userId")`;
await sql.end();
console.log("agency_announcements migration OK");
